"use client";

import { useEffect, useState } from "react";
import { getRdqaScorecard, getRdqaTrend, type RdqaScorecard, type RdqaTrend } from "@/lib/dashboard";
import { AppShell } from "@/components/layout/AppShell";
import { ChartCard, LineChart, type LineSeries } from "@/components/ui/Charts";
import { StatTile } from "@/components/ui/StatTile";

const pct = (v: number | null | undefined) => (v == null ? "—" : `${Math.round(v * 100)}%`);

function scoreColor(s: number | null) {
  if (s == null) return "var(--cv-text-muted)";
  if (s >= 80) return "var(--cv-success-text)";
  if (s >= 60) return "var(--cv-warning-text)";
  return "var(--cv-danger-text)";
}

export default function RdqaPage() {
  const [sc, setSc] = useState<RdqaScorecard | null>(null);
  const [trend, setTrend] = useState<RdqaTrend | null>(null);

  useEffect(() => {
    getRdqaScorecard().then(setSc).catch(() => setSc(null));
    getRdqaTrend().then(setTrend).catch(() => setTrend(null));
  }, []);

  const o = sc?.overall ?? {};
  const trendSeries: LineSeries[] = trend
    ? [{ name: "Mean extraction confidence", points: trend.points.map((p) => ({ x: p.x, y: p.rate == null ? null : Math.round(p.rate * 100) })) }]
    : [];

  return (
    <AppShell
      title="Data quality (RDQA)"
      subtitle="Continuous Routine Data Quality Assessment — the grant-condition audit, generated continuously"
      allowedRoles={["facility_lead", "organisation_user"]}
    >
      <div style={{ display: "flex", flexDirection: "column", gap: 16 }}>
        <div style={{ display: "grid", gridTemplateColumns: "repeat(4, 1fr)", gap: 14 }}>
          <StatTile status={o.mean_score != null && o.mean_score >= 80 ? "success" : "warning"} label="Mean RDQA score" value={o.mean_score ?? "—"} />
          <StatTile status="neutral" label="Mean confidence" value={pct(o.mean_confidence)} />
          <StatTile status="neutral" label="Facilities assessed" value={o.facilities_assessed ?? 0} />
          <StatTile status={(o.total_open_flags ?? 0) > 0 ? "warning" : "success"} label="Open template flags" value={o.total_open_flags ?? 0} />
        </div>

        <ChartCard
          title="Extraction confidence over time"
          subtitle="Mean confidence of published fields, by publish month"
          note="A meta-signal on how well each facility's paper registers extract against the template — generated by the intake pipeline itself."
        >
          {!trend || trend.points.length === 0 ? (
            <p style={{ fontSize: 12, color: "var(--cv-text-muted)" }}>Confidence trend appears once intakes publish across more than one month.</p>
          ) : (
            <LineChart series={trendSeries} unit="percent" />
          )}
        </ChartCard>

        <ChartCard
          title="RDQA scorecard"
          subtitle="Per facility — download as your grant-condition data-quality report"
          note="Score (0–100) = 45% confidence + 45% completeness − implausible-value & open-flag penalties. Weights are operational, not clinical."
          exportCsv={sc ? {
            name: "rdqa-scorecard",
            header: ["Facility", "Region", "Rows", "Score", "Confidence", "Completeness", "Implausible rate", "Open flags", "Avg days to publish"],
            rows: sc.facilities.map((f) => [f.name, f.region, f.rows, f.score, pct(f.avg_extraction_confidence), pct(f.completeness), pct(f.implausible_rate), f.open_template_flags, f.avg_days_to_publish]),
          } : undefined}
        >
          {!sc || sc.facilities.length === 0 ? (
            <p style={{ fontSize: 12, color: "var(--cv-text-muted)" }}>No published data to assess yet.</p>
          ) : (
            <div style={{ overflowX: "auto" }}>
              <table style={{ width: "100%", borderCollapse: "collapse", fontSize: 11.5 }}>
                <thead>
                  <tr style={{ textAlign: "left", color: "var(--cv-text-muted)" }}>
                    <th style={{ padding: "6px 8px" }}>Facility</th>
                    <th style={{ padding: "6px 8px" }}>Score</th>
                    <th style={{ padding: "6px 8px" }}>Confidence</th>
                    <th style={{ padding: "6px 8px" }}>Completeness</th>
                    <th style={{ padding: "6px 8px" }}>Implausible</th>
                    <th style={{ padding: "6px 8px" }}>Open flags</th>
                    <th style={{ padding: "6px 8px" }}>Days to publish</th>
                  </tr>
                </thead>
                <tbody>
                  {sc.facilities.map((f) => (
                    <tr key={f.facility_id} style={{ borderTop: "1px solid var(--cv-hairline)" }}>
                      <td style={{ padding: "6px 8px", color: "var(--cv-text-primary)", fontWeight: 600 }}>{f.name}<div style={{ fontSize: 10, color: "var(--cv-text-muted)" }}>{f.region}</div></td>
                      <td className="cv-num" style={{ padding: "6px 8px", fontWeight: 700, color: scoreColor(f.score) }}>{f.score ?? "—"}</td>
                      <td className="cv-num" style={{ padding: "6px 8px" }}>{pct(f.avg_extraction_confidence)}</td>
                      <td className="cv-num" style={{ padding: "6px 8px" }}>{pct(f.completeness)}</td>
                      <td className="cv-num" style={{ padding: "6px 8px" }}>{pct(f.implausible_rate)}</td>
                      <td className="cv-num" style={{ padding: "6px 8px" }}>{f.open_template_flags}</td>
                      <td className="cv-num" style={{ padding: "6px 8px" }}>{f.avg_days_to_publish ?? "—"}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </ChartCard>
      </div>
    </AppShell>
  );
}
